/// Deterministic LCG so the cross-checks are reproducible.
fn lcg(state: &mut u64) -> u64 {
    *state = state
        .wrapping_mul(6364136223846793005)
        .wrapping_add(1442695040888963407);
    *state >> 33
}

#[test]
fn pinned_oracle_vectors_match() {
    for (i, (input, expected)) in PINNED.iter().enumerate() {
        let mut block = *input;
        idct_w0(&mut block);
        assert_eq!(&block[..], &expected[..], "pinned vector {i}");
    }
}

#[test]
fn zero_block_maps_to_zero() {
    let mut block = [0i16; 64];
    idct_w0(&mut block);
    assert_eq!(block, [0i16; 64]);
    let mut block = [0i16; 64];
    fdct_w0(&mut block);
    assert_eq!(block, [0i16; 64]);
}

#[test]
fn output_range_is_clipped() {
    let mut state = 7u64;
    for _ in 0..500 {
        let mut block = [0i16; 64];
        for v in block.iter_mut() {
            *v = (lcg(&mut state) % 4096) as i16 - 2048;
        }
        idct_w0(&mut block);
        assert!(block.iter().all(|&v| (-256..=255).contains(&v)));
    }
    let mut block = [2047i16; 64];
    fdct_w0(&mut block);
    assert!(block.iter().all(|&v| (-2048..=2047).contains(&v)));
}

/// §W.5.3 NOTE — "this fixed-point IDCT is compliant with Annex A":
/// against the crate's f64 reference kernel the per-sample error stays
/// within the A.7 peak bound of 1 on coefficient blocks in the video
/// working range.
#[test]
fn annex_a_agreement_with_reference_kernel() {
    let mut state = 450u64;
    let check = |coefs: &[i16; 64]| {
        let mut fx = *coefs;
        idct_w0(&mut fx);
        let reference = idct_8x8(coefs);
        for (i, (&a, &b)) in fx.iter().zip(reference.iter()).enumerate() {
            let b = (b as i32).clamp(-256, 255);
            let err = (a as i32 - b).abs();
            assert!(
                err <= 1,
                "sample {i}: fixed-point {a} vs reference {b} (err {err})"
            );
        }
    };
    // Small-magnitude random coefficient blocks (the sparse
    // high-frequency shapes real residuals produce).
    for range in [5i32, 32, 64] {
        for _ in 0..300 {
            let mut coefs = [0i16; 64];
            for v in coefs.iter_mut() {
                *v = (lcg(&mut state) as i32 % (2 * range) - range) as i16;
            }
            check(&coefs);
        }
    }
    // Content-derived blocks: forward-transform full-range spatial
    // data, so the coefficient energy distribution is the one video
    // actually presents to the IDCT (Annex A measures over decodable
    // content, not arbitrary coefficient noise, which can exceed the
    // 16-bit fixed-point dynamic range by design).
    for _ in 0..300 {
        let mut spatial = [0i16; 64];
        for v in spatial.iter_mut() {
            *v = (lcg(&mut state) % 512) as i16 - 256;
        }
        let coefs_f = fdct_8x8(&spatial);
        let mut coefs = [0i16; 64];
        for (c, &f) in coefs.iter_mut().zip(coefs_f.iter()) {
            *c = f.round().clamp(-2048.0, 2047.0) as i16;
        }
        check(&coefs);
    }
}

/// The FDCT → IDCT pair reconstructs spatial data closely (both ends
/// are the listing's own fixed-point approximations, so allow a small
/// bounded error rather than exactness).
#[test]
fn fdct_idct_round_trip_is_tight() {
    let mut state = 99u64;
    for _ in 0..300 {
        let mut spatial = [0i16; 64];
        for v in spatial.iter_mut() {
            *v = (lcg(&mut state) % 512) as i16 - 256;
        }
        let mut block = spatial;
        fdct_w0(&mut block);
        idct_w0(&mut block);
        for (i, (&a, &b)) in block.iter().zip(spatial.iter()).enumerate() {
            let b = (b as i32).clamp(-256, 255);
            assert!(
                (a as i32 - b).abs() <= 2,
                "sample {i}: round trip {a} vs source {b}"
            );
        }
    }
}
